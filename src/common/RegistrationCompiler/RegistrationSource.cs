using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace RegistrationCompiler;

/// <summary>
/// Connects adapter-supplied registration statements across a compilation and its references.
/// Only the generated marker and helper are emitted into a producer's assembly.
/// </summary>
public static class RegistrationSource
{
    /// <summary>Emits one public helper whose registration target is named <c>target</c>.</summary>
    public static string EmitProducer(string assemblyName, string adapterId, string targetType, IEnumerable<string> statements)
    {
        var ns = ProducerNamespace(assemblyName, adapterId);
        var source = new StringBuilder()
            .Append("// <auto-generated/>\n#nullable enable\n")
            .Append("[assembly: global::").Append(ns).Append(".ProducerAttribute(")
            .Append(SymbolDisplay.FormatLiteral(adapterId, quote: true)).Append(", typeof(global::")
            .Append(ns).Append(".Bindings))]\nnamespace ").Append(ns).Append("\n{\n")
            .Append("    [global::System.AttributeUsage(global::System.AttributeTargets.Assembly)]\n")
            .Append("    internal sealed class ProducerAttribute : global::System.Attribute\n    {\n")
            .Append("        public ProducerAttribute(string adapterId, global::System.Type helper) { }\n    }\n")
            .Append("    public static class Bindings\n    {\n")
            .Append("        public static void Register(").Append(targetType).Append(" target)\n        {\n");
        foreach (var statement in statements.OrderBy(s => s, StringComparer.Ordinal))
            source.Append("            ").Append(statement).Append('\n');
        return source.Append("        }\n    }\n}\n").ToString();
    }

    /// <summary>Produces calls to the local and referenced helpers belonging to this adapter.</summary>
    public static IEnumerable<string> ImportCalls(Compilation compilation, string adapterId, string targetExpression, bool includeLocalProducer)
    {
        var helpers = new SortedSet<string>(StringComparer.Ordinal);
        if (includeLocalProducer)
            helpers.Add("global::" + ProducerNamespace(compilation.Assembly.Name, adapterId) + ".Bindings");

        foreach (var assembly in compilation.SourceModule.ReferencedAssemblySymbols)
        {
            var marker = assembly.GetTypeByMetadataName(ProducerNamespace(assembly.Name, adapterId) + ".ProducerAttribute");
            if (marker is null)
                continue;
            foreach (var attribute in assembly.GetAttributes())
            {
                if (!SymbolEqualityComparer.Default.Equals(attribute.AttributeClass, marker)
                    || attribute.ConstructorArguments.Length != 2
                    || attribute.ConstructorArguments[0].Value is not string id || id != adapterId
                    || attribute.ConstructorArguments[1].Kind != TypedConstantKind.Type
                    || attribute.ConstructorArguments[1].Value is not INamedTypeSymbol helper
                    || !SymbolEqualityComparer.Default.Equals(helper.ContainingAssembly, assembly))
                    continue;
                helpers.Add(helper.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
            }
        }
        return helpers.Select(helper => helper + ".Register(" + targetExpression + ");");
    }

    private static string ProducerNamespace(string assemblyName, string adapterId) =>
        "RegistrationCompiler.Generated.P" + Identifier(assemblyName) + ".A" + Identifier(adapterId);

    // Escape underscores too, so a literal escape sequence and the character it represents stay distinct.
    private static string Identifier(string value)
    {
        var result = new StringBuilder(value.Length);
        foreach (var c in value)
        {
            if (c is >= 'a' and <= 'z' or >= 'A' and <= 'Z' or >= '0' and <= '9')
                result.Append(c);
            else
                result.Append('_').Append(((int)c).ToString("X4", CultureInfo.InvariantCulture));
        }
        return result.ToString();
    }
}
