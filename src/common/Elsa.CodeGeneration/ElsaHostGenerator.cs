using System;
using System.Linq;
using System.Text;
using Elsa.CodeGeneration.Compiler;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Elsa.CodeGeneration.Generators;

/// <summary>
/// Emits build information and implements a legacy bootstrap when the application declares one.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ElsaHostGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var settings = context.AnalyzerConfigOptionsProvider.Select(static (options, _) => CompilerSettings.Read(options.GlobalOptions));
        var marker = settings.Select(static (value, _) => Marker(value));
        context.RegisterSourceOutput(marker, static (production, source) =>
        {
            if (source is not null)
                production.AddSource("ElsaGenerationBuildMarker.g.cs", SourceText.From(source, Encoding.UTF8));
        });
        var bootstrap = context.CompilationProvider.Combine(settings).Select(static (input, cancellationToken) =>
        {
            if (!input.Right.IsHost || !input.Right.GenerateMetadata || input.Right.IsManual
                || !CompilerContract.HasAuthoredHost(input.Left))
                return HostGenerationOutput.Empty;
            var contract = CompilerContract.Validate(input.Left, input.Right, cancellationToken);
            return contract.Success
                ? new HostGenerationOutput(Bootstrap(input.Right, contract), HostFailure.None, string.Empty, Location.None)
                : new HostGenerationOutput(null, contract.Failure, contract.Message, contract.Location);
        });
        context.RegisterSourceOutput(bootstrap, static (production, output) =>
        {
            if (output.Failure != HostFailure.None)
                production.ReportDiagnostic(Diagnostic.Create(CompilerDiagnostics.For(output.Failure), output.Location, output.Message));
            if (output.Source is not null)
                production.AddSource(CompilerContract.BootstrapHintName, SourceText.From(output.Source, Encoding.UTF8));
        });
    }

    private static string? Marker(CompilerSettings settings)
    {
        if (!settings.GenerateMetadata || (!settings.IsGenerated && !settings.IsDynamic) || (!settings.IsCompiler && !settings.IsManual) || settings.Schema != "1")
            return null;
        return "// <auto-generated/>\n#nullable enable\nnamespace Elsa.CodeGeneration\n{\n"
            + "    internal static class ElsaGenerationBuildMarker\n    {\n"
            + "        internal const int ModuleExportSchemaVersion = 1;\n"
            + "        internal const string EffectiveExecutionMode = \"" + (settings.IsGenerated ? "Generated" : "Dynamic") + "\";\n"
            + "        internal const string HostBootstrap = \"" + (settings.IsManual ? "Manual" : "Compiler") + "\";\n"
            + "        internal const bool IsHost = " + (settings.IsHost ? "true" : "false") + ";\n"
            + "    }\n}\n";
    }

    private static string Bootstrap(CompilerSettings settings, HostContractResult contract)
    {
        var parameters = contract.Entry!.Parameters.Select(parameter => Escape(parameter.Name)).ToArray();
        var services = parameters[0];
        var policy = parameters[1];
        var body = settings.IsGenerated
            ? "            return global::Elsa.Features.Services.FeatureModuleCatalogBuilder.CreateModule(" + services + ", global::Elsa.CodeGeneration.ElsaHost.GetModuleExports(), " + policy + ");\n"
            : "            return global::Elsa.CodeGeneration.ElsaHost.CreateDynamicModule(" + services + ", " + policy + ");\n";
        return "// <auto-generated/>\n#nullable enable\nnamespace Elsa.CodeGeneration\n{\n"
            + "    internal static partial class ElsaHost\n    {\n"
            + "        internal static partial global::Elsa.Features.Services.IModule CreateModule(global::Microsoft.Extensions.DependencyInjection.IServiceCollection " + services
            + ", global::Elsa.Features.Models.CompositionPolicy " + policy + ")\n        {\n"
            + body + "        }\n    }\n}\n";
    }

    // Successful incremental values contain only source text. Error values retain the current
    // source location so a diagnostic still identifies the authored declaration when trees change.
    private sealed class HostGenerationOutput : IEquatable<HostGenerationOutput>
    {
        internal static readonly HostGenerationOutput Empty = new(null, HostFailure.None, string.Empty, Location.None);
        internal HostGenerationOutput(string? source, HostFailure failure, string message, Location location)
        {
            Source = source;
            Failure = failure;
            Message = message;
            Location = location;
        }
        internal string? Source { get; }
        internal HostFailure Failure { get; }
        internal string Message { get; }
        internal Location Location { get; }
        public bool Equals(HostGenerationOutput? other) => other is not null && Failure == other.Failure
            && string.Equals(Source, other.Source, StringComparison.Ordinal) && string.Equals(Message, other.Message, StringComparison.Ordinal)
            && Location.Equals(other.Location);
        public override bool Equals(object? obj) => obj is HostGenerationOutput other && Equals(other);
        public override int GetHashCode()
        {
            unchecked
            {
                var hash = (int)Failure;
                hash = hash * 31 + (Source is null ? 0 : StringComparer.Ordinal.GetHashCode(Source));
                hash = hash * 31 + StringComparer.Ordinal.GetHashCode(Message);
                return hash * 31 + Location.GetHashCode();
            }
        }
    }

    private static string Escape(string identifier) => SyntaxFacts.GetKeywordKind(identifier) != SyntaxKind.None || SyntaxFacts.GetContextualKeywordKind(identifier) != SyntaxKind.None ? "@" + identifier : identifier;
}