using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using Elsa.CodeGeneration.Compiler;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Elsa.CodeGeneration.Generators;

/// <summary>
/// Emits only the selected compiler bootstrap; feature bindings remain in authored typed exports.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ElsaHostGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var settings = context.AnalyzerConfigOptionsProvider.Select(static (options, _) => CompilerSettings.Read(options.GlobalOptions));
        var marker = settings.Select(static (value, _) => Marker(value));
        context.RegisterSourceOutput(marker, static (production, source) =>
        {
            if (source is not null)
                production.AddSource("ElsaGenerationBuildMarker.g.cs", SourceText.From(source, Encoding.UTF8));
        });
        var bootstrap = context.CompilationProvider.Combine(settings).Select(static (input, cancellationToken) =>
        {
            if (!input.Right.IsHost || !input.Right.GenerateMetadata || !input.Right.IsCompiler)
                return null;
            var contract = CompilerContract.Validate(input.Left, input.Right, cancellationToken);
            return contract.Success ? Bootstrap(input.Right, contract) : null;
        });
        context.RegisterSourceOutput(bootstrap, static (production, source) =>
        {
            if (source is not null)
                production.AddSource(CompilerContract.BootstrapHintName, SourceText.From(source, Encoding.UTF8));
        });
    }

    private static string? Marker(CompilerSettings settings)
    {
        if (!settings.GenerateMetadata || (!settings.IsGenerated && !settings.IsDynamic) || settings.Schema != "1")
            return null;
        return "// <auto-generated/>\n#nullable enable\nnamespace Elsa.CodeGeneration\n{\n"
            + "    internal static class ElsaGenerationBuildMarker\n    {\n"
            + "        internal const int ModuleExportSchemaVersion = 1;\n"
            + "        internal const string EffectiveExecutionMode = \"" + (settings.IsGenerated ? "Generated" : "Dynamic") + "\";\n"
            + "        internal const string HostBootstrap = \"" + (settings.IsManual ? "Manual" : "Compiler") + "\";\n"
            + "        internal const bool IsHost = " + (settings.IsHost ? "true" : "false") + ";\n"
            + "    }\n}\n";
    }

    private static string Bootstrap(CompilerSettings settings, HostContractResult contract)
    {
        var parameters = contract.Entry!.Parameters.Select(parameter => Escape(parameter.Name)).ToArray();
        var reserved = new HashSet<string>(contract.Entry.Parameters.Select(parameter => parameter.Name), StringComparer.Ordinal);
        var services = parameters[0];
        var policy = parameters[1];
        var exports = LocalName("__elsaExports");
        var builder = LocalName("__elsaBuilder");
        var export = LocalName("__elsaExport");
        var body = settings.IsGenerated
            ? "            var " + exports + " = global::Elsa.CodeGeneration.ElsaHost.GetModuleExports();\n"
                + "            if (" + exports + " is null || " + exports + ".Length == 0)\n"
                + "                throw new global::System.InvalidOperationException(\"ElsaHost.GetModuleExports must return at least one selected FeatureModuleExport.\");\n"
                + "            var " + builder + " = new global::Elsa.Features.Services.FeatureModuleCatalogBuilder();\n"
                + "            foreach (var " + export + " in " + exports + ")\n            {\n"
                + "                if (" + export + " is null)\n"
                + "                    throw new global::System.InvalidOperationException(\"ElsaHost.GetModuleExports returned a null module export.\");\n"
                + "                " + builder + ".Add(" + export + ");\n            }\n"
                + "            return new global::Elsa.Features.Implementations.Module(" + services + ", " + builder + ".Build(), " + policy + ");\n"
            : "            return global::Elsa.CodeGeneration.ElsaHost.CreateDynamicModule(" + services + ", " + policy + ");\n";
        return "// <auto-generated/>\n#nullable enable\nnamespace Elsa.CodeGeneration\n{\n"
            + "    internal static partial class ElsaHost\n    {\n"
            + "        internal static partial global::Elsa.Features.Services.IModule CreateModule(global::Microsoft.Extensions.DependencyInjection.IServiceCollection " + services
            + ", global::Elsa.Features.Models.CompositionPolicy " + policy + ")\n        {\n"
            + body + "        }\n    }\n}\n";

        string LocalName(string stem)
        {
            var name = stem;
            var suffix = 0;
            while (!reserved.Add(name))
                name = stem + (++suffix).ToString(CultureInfo.InvariantCulture);
            return name;
        }
    }

    private static string Escape(string identifier) => SyntaxFacts.GetKeywordKind(identifier) != SyntaxKind.None || SyntaxFacts.GetContextualKeywordKind(identifier) != SyntaxKind.None ? "@" + identifier : identifier;
}