using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Flamme.ActivityGenerator;

[Generator]
public sealed class ActivityGenerator : IIncrementalGenerator
{
    internal const string Workflows = ActivityDiscovery.Workflows;
    internal const string Attributes = Workflows + "Attributes.";
    internal const string Models = Workflows + "Models.";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var candidates = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => ActivityDiscovery.IsCandidate(node),
            static (syntax, _) => syntax.Node).Collect();
        context.RegisterSourceOutput(context.CompilationProvider.Combine(candidates),
            static (output, input) => Generate(output, input.Left, input.Right));
    }

    private static void Generate(SourceProductionContext output, Compilation compilation, ImmutableArray<SyntaxNode> syntax)
    {
        if (ActivityDiscovery.Discover(compilation, syntax, output.CancellationToken, output.ReportDiagnostic) is not { } discovery)
            return;

        (compilation, var descriptors, var explicitSites, var inferred, var bridgeOwners, var explicitContexts) = discovery;
        var rows = descriptors.OrderBy(row => TypeName(row.Key), StringComparer.Ordinal).ToArray();
        var producerNamespace = ActivityGeneratedNames.ForProducer(compilation.Assembly.Name);
        var source = new StringBuilder($$"""
            // <auto-generated />
            #nullable enable
            #pragma warning disable CS0612, CS0618, CS8600, CS8601, CS8603, CS8604, CS8619, CS8620, CS8625
            using System;
            using System.Collections.Generic;
            using System.Reflection;
            using System.Runtime.CompilerServices;
            using Flamme.Workflows;
            using Flamme.Workflows.Models;

            namespace {{producerNamespace}}
            {
            internal sealed class ActivityModule : ActivityContext
            {

            """);
        var names = new Dictionary<INamedTypeSymbol, string>(SymbolEqualityComparer.Default);
        for (var index = 0; index < rows.Length; ++index)
        {
            var row = rows[index];
            var name = "Row" + index;
            var rowSource = new StringBuilder();
            try
            {
                new ActivityEmitter(compilation, row.Key, name, inferred.Contains(row.Key)).Emit(rowSource);
                source.Append(rowSource);
                names.Add(row.Key, name);
            }
            catch (BindingException error)
            {
                explicitSites.TryGetValue(row.Key, out var request);
                Report(output, compilation, row.Key, error.Binding, error.Message, error.Sites, request);
            }
        }

        source.AppendLine("    internal static readonly ActivityModule Default = new();");
        source.AppendLine($"    private ActivityModule() : base(typeof(ActivityModule).Assembly, [{string.Join(", ", names.Values)}], Exported()) {{ }}");
        source.AppendLine($"    private static Type[] Exported() => [{string.Join(", ", rows.Where(row => row.Value && names.ContainsKey(row.Key)).Select(row => TypeOf(row.Key)))}];");
        source.AppendLine("    [ModuleInitializer] internal static void Register() => ActivityContextRegistry.Register(Default);");
        source.AppendLine("}");
        source.AppendLine("}");
        source.AppendLine($"namespace {ActivityGeneratedNames.Namespace}");
        source.AppendLine("{");
        foreach (var owner in bridgeOwners.OrderBy(TypeName, StringComparer.Ordinal))
        {
            if (descriptors.ContainsKey(owner) && !names.ContainsKey(owner))
                continue;

            var bridgeSource = new StringBuilder();
            try
            {
                new ActivityEmitter(compilation, owner, BridgeName(owner)).EmitProducerCallbacks(bridgeSource);
                source.Append(bridgeSource);
            }
            catch (BindingException error)
            {
                Report(output, compilation, owner, error.Binding, error.Message, error.Sites);
            }
        }
        source.AppendLine("}");
        foreach (var pair in explicitContexts.OrderBy(pair => TypeName(pair.Key), StringComparer.Ordinal))
            EmitContext(output, compilation, source, pair.Key, producerNamespace, pair.Value.Where(names.ContainsKey).Select(type => names[type]));
        output.AddSource("Flamme.ActivityModule.g.cs", source.ToString());
    }

    private static void EmitContext(SourceProductionContext output, Compilation compilation, StringBuilder source,
        INamedTypeSymbol context, string producerNamespace, IEnumerable<string> rows)
    {
        var declaration = context.DeclaringSyntaxReferences
            .Select(reference => reference.GetSyntax(output.CancellationToken)).OfType<ClassDeclarationSyntax>().FirstOrDefault();
        if (declaration is null || !declaration.Modifiers.Any(SyntaxKind.PartialKeyword) ||
            context.ContainingType is not null || context.Arity != 0 || context.IsAbstract)
        {
            Report(output, compilation, context, "context declaration", "Use a non-abstract, top-level, non-generic partial class.");
            return;
        }

        var ns = context.ContainingNamespace;
        if (!ns.IsGlobalNamespace)
            source.AppendLine($"namespace {ns} {{");
        var name = Identifier(context.Name);
        source.AppendLine($"partial class {name}");
        source.AppendLine("{");
        source.AppendLine($"    public static {name} Default {{ get; }} = new();");
        var bindings = rows.Select(row => $"global::{producerNamespace}.{ActivityGeneratedNames.ModuleName}.{row}");
        source.AppendLine($"    private {name}() : base(typeof({name}).Assembly, [{string.Join(", ", bindings)}], []) {{ }}");
        source.AppendLine("}");
        if (!ns.IsGlobalNamespace)
            source.AppendLine("}");
    }

    private static void Report(SourceProductionContext output, Compilation compilation, INamedTypeSymbol activity,
        string binding, string message, Location[]? sites = null, Location? request = null) =>
        ActivityDiscovery.Report(output.ReportDiagnostic, compilation, activity, binding, message, sites, request);

    internal static Location[] SourceLocations(ISymbol symbol) =>
        symbol.Locations.Where(location => location.IsInSource).ToArray();

    internal static IEnumerable<INamedTypeSymbol> Hierarchy(INamedTypeSymbol type) => ActivityDiscovery.Hierarchy(type);

    internal static bool Is(ITypeSymbol? type, string metadataName) => ActivityDiscovery.Is(type, metadataName);

    internal static bool IsAssignableTo(ITypeSymbol type, string metadataName) =>
        Is(type, metadataName) || type is INamedTypeSymbol named && Hierarchy(named).Any(owner => Is(owner, metadataName)) ||
        type.AllInterfaces.Any(iface => Is(iface, metadataName));

    internal static string MetadataName(INamedTypeSymbol type) => ActivityDiscovery.MetadataName(type);

    internal static string BridgeName(INamedTypeSymbol owner)
    {
        // Include the assembly identity so unrelated references can expose their own bridge.
        var key = owner.ContainingAssembly.Name + ":" + MetadataName(owner.OriginalDefinition);
        var hash = 14695981039346656037UL;
        foreach (var character in key)
            hash = unchecked((hash ^ character) * 1099511628211UL);
        return "ActivityCallbacks_" + hash.ToString("x16", System.Globalization.CultureInfo.InvariantCulture);
    }

    internal static string TypeName(ITypeSymbol type) => ActivityDiscovery.TypeName(type);

    internal static string TypeOf(ITypeSymbol type) => $"typeof({TypeName(type)})";

    internal static string Identifier(string name) => SyntaxFacts.GetKeywordKind(name) == SyntaxKind.None ? name : "@" + name;

    internal static string Quote(string text) => SymbolDisplay.FormatLiteral(text, true);

    internal static string Boolean(bool value) => value ? "true" : "false";
}

internal sealed class BindingException(string binding, string message, params Location[] sites) : Exception(message)
{
    public string Binding { get; } = binding;
    public Location[] Sites { get; } = sites;
}
